// Merge ar missing keys with en fallback (kept minimal; ar mirrors en)
export const translations: Record<Lang, Record<string, string>> = {
  en,
  ar: { ...en, ...ar },
};

export const DEFAULT_LANG: Lang = "ar";
export const COOKIE_NAME = "fatora_lang";
export const SUPPORTED_LANGS: Lang[] = ["en", "ar"];

export function isRTL(lang: Lang): boolean {
  return lang === "ar";
}

export function t(key: TranslationKey, lang: Lang, params?: Record<string, string>): string {
  const dict = translations[lang];
  let text = dict[key] || dict[key as string] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`{{${k}}}`, "g"), v);
    });
  }
  return text;
}

export function getTranslations(lang: Lang) {
  return (key: TranslationKey, params?: Record<string, string>) => t(key, lang, params);
}
